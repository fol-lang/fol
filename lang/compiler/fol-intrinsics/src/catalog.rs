pub const fn intrinsic_registry() -> &'static [IntrinsicEntry] {
    INTRINSICS
}

pub const fn all_intrinsics() -> &'static [IntrinsicEntry] {
    intrinsic_registry()
}

pub fn intrinsic_by_canonical_name(name: &str) -> Option<&'static IntrinsicEntry> {
    intrinsic_registry().iter().find(|entry| entry.name == name)
}

pub fn intrinsic_by_alias(alias: &str) -> Option<&'static IntrinsicEntry> {
    intrinsic_registry()
        .iter()
        .find(|entry| entry.aliases.contains(&alias))
}

pub fn intrinsics_for_surface(surface: IntrinsicSurface) -> Vec<&'static IntrinsicEntry> {
    intrinsic_registry()
        .iter()
        .filter(|entry| entry.surface == surface)
        .collect()
}

pub fn intrinsic_by_id(id: IntrinsicId) -> Option<&'static IntrinsicEntry> {
    intrinsic_registry().iter().find(|entry| entry.id == id)
}

pub fn reserved_intrinsic_for_surface(
    surface: IntrinsicSurface,
    name: &str,
) -> Option<&'static IntrinsicEntry> {
    intrinsic_registry().iter().find(|entry| {
        entry.surface == surface && (entry.name == name || entry.aliases.contains(&name))
    })
}

pub fn is_reserved_intrinsic_name_for_surface(surface: IntrinsicSurface, name: &str) -> bool {
    reserved_intrinsic_for_surface(surface, name).is_some()
}

pub fn lowering_mode_for_intrinsic(id: IntrinsicId) -> Option<IntrinsicLoweringMode> {
    intrinsic_by_id(id).map(|entry| entry.lowering_mode)
}

pub fn roadmap_for_intrinsic(id: IntrinsicId) -> Option<IntrinsicRoadmap> {
    intrinsic_by_id(id).map(|entry| match entry.id.index() {
        0..=8 | 12 | 13 => IntrinsicRoadmap::CurrentV1,
        9 | 10 | 11 | 14 | 15 | 21 | 22 => IntrinsicRoadmap::LikelyV1x,
        16 => IntrinsicRoadmap::V4,
        23..=36 => IntrinsicRoadmap::CoreStdInstead,
        37..=56 => IntrinsicRoadmap::V2,
        // The terminal, string, time, and OS hooks are shipped and wrapped by
        // the bundled std, so they are current surface rather than roadmap.
        57..=80 => IntrinsicRoadmap::CurrentV1,
        _ => IntrinsicRoadmap::V2,
    })
}

pub fn intrinsics_for_roadmap(roadmap: IntrinsicRoadmap) -> Vec<&'static IntrinsicEntry> {
    intrinsic_registry()
        .iter()
        .filter(|entry| roadmap_for_intrinsic(entry.id) == Some(roadmap))
        .collect()
}

pub fn backend_role_for_intrinsic(id: IntrinsicId) -> Option<IntrinsicBackendRole> {
    intrinsic_by_id(id).and_then(|entry| match entry.id.index() {
        0..=6 => Some(IntrinsicBackendRole::PureOp),
        7 | 12 => Some(IntrinsicBackendRole::TargetHelper),
        // 8 = echo; 57..=80 = the terminal, string, time, OS, and CLI hooks;
        // 81..=89 = the numeric and character conversions.
        // 36 = sqrt, promoted in place from its Deferred placeholder rather than
        // shadowed by a second entry.
        // 36 = sqrt and 37..=46 = the bitwise family, all promoted in place from
        // their Deferred placeholders rather than shadowed by second entries.
        8 | 36..=46 | 57..=101 => Some(IntrinsicBackendRole::RuntimeHook),
        13 => Some(IntrinsicBackendRole::ControlEffect),
        _ => None,
    })
}

pub fn implemented_intrinsics_for_backend_role(
    role: IntrinsicBackendRole,
) -> Vec<&'static IntrinsicEntry> {
    intrinsic_registry()
        .iter()
        .filter(|entry| backend_role_for_intrinsic(entry.id) == Some(role))
        .collect()
}

pub fn intrinsics_for_lowering_mode(
    lowering_mode: IntrinsicLoweringMode,
) -> Vec<&'static IntrinsicEntry> {
    intrinsic_registry()
        .iter()
        .filter(|entry| entry.lowering_mode == lowering_mode)
        .collect()
}
